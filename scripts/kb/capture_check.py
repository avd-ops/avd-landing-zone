"""Ask for a knowledge base entry when code changes without one (decision 0011).

Two modes, both git-only and stdlib-only, so a repo without the KB scripts can copy this one file:

  python3 scripts/kb/capture_check.py hook
      A Claude Code Stop hook. Reads the hook's JSON on stdin. If files outside the KB changed and
      nothing in the KB did, it asks for a lesson (block mode) or posts a reminder (warn mode).
      It asks once per session for a given set of changed files, never twice in a row, and never
      fails the session on its own errors.

  python3 scripts/kb/capture_check.py pr --base origin/main
      The kb-capture PR check. Reads the pull request from $GITHUB_EVENT_PATH and fails when code
      changed without a KB change, unless the PR has the `no-kb` label and a "No KB entry:" line,
      or (in a repo without a KB) a `KB: <link>` to a KB repo it feeds.

Settings come from docs/knowledge/kb.toml in a repo with a KB, or .claude/kb-capture.toml in one
without:

  capture_hook = "block"            # or "warn"
  capture_ignore = ["dist/**"]      # extra paths that don't count as code changes
  kb_repos = ["owner/kb-repo"]      # repo without a KB: the KB repos a `KB:` link may point at
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KB_PATH = "docs/knowledge/"
NO_KB_LABEL = "no-kb"
# Never code: generated by build.py, or regenerated by package tooling.
DEFAULT_IGNORE = ["llms.txt", "*.lock", "**/*.lock", "package-lock.json", "**/package-lock.json",
                  "poetry.lock", "uv.lock"]
# The family's own automation opens these; they carry no lesson.
BOT_AUTHORS = {"github-actions[bot]", "dependabot[bot]", "renovate[bot]"}
NO_KB_REASON = re.compile(r"^\s*No KB entry:\s*\S", re.I | re.M)
KB_LINK = re.compile(r"^\s*KB:\s*(https://github\.com/([^/\s]+/[^/\s]+)/\S*)", re.I | re.M)

HOOK_REASON = ("Files changed in this session but nothing under docs/knowledge/ did "
               "(decision 0011). Before you finish, write what you learned on its topic page, or say "
               "in one line why there is nothing to capture.")
HOOK_REASON_NO_KB = ("Files changed in this session and this repo has no knowledge base of its own "
                     "(decision 0011). Before you finish, record the lesson in the KB this repo "
                     "feeds ({kbs}) and link it from the PR body as `KB: <link>`, or say in one line "
                     "why there is nothing to capture.")


def load_config(root: Path = ROOT) -> dict:
    """Settings, from the KB's kb.toml or, in a repo without a KB, .claude/kb-capture.toml."""
    kb_toml = root / KB_PATH / "kb.toml"
    side = root / ".claude" / "kb-capture.toml"
    has_kb = kb_toml.exists()
    path = kb_toml if has_kb else side
    cfg = {}
    if path.exists():
        with path.open("rb") as f:
            cfg = tomllib.load(f)
    mode = cfg.get("capture_hook", "block")
    if mode not in ("block", "warn", "off"):
        mode = "block"
    return {
        "has_kb": has_kb,
        "mode": mode,
        "ignore": DEFAULT_IGNORE + list(cfg.get("capture_ignore", [])),
        "kb_repos": [r.lower() for r in cfg.get("kb_repos", [])],
    }


def ignored(path: str, patterns: list[str]) -> bool:
    return any(fnmatch.fnmatchcase(path, p) for p in patterns)


def classify(files: list[str], ignore: list[str]) -> tuple[list[str], bool]:
    """(code files, whether any KB file changed) for a list of changed paths."""
    kb = any(f.startswith(KB_PATH) for f in files)
    code = [f for f in files if not f.startswith(KB_PATH) and not ignored(f, ignore)]
    return code, kb


def git(*args: str, root: Path = ROOT) -> list[str]:
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=True)
    return [line for line in r.stdout.splitlines() if line.strip()]


def default_branch(root: Path = ROOT) -> str:
    try:
        ref = git("symbolic-ref", "--short", "refs/remotes/origin/HEAD", root=root)[0]
        return ref
    except (subprocess.CalledProcessError, IndexError):
        return "origin/main"


def session_changes(root: Path = ROOT) -> list[str]:
    """Files changed on this branch and in the working tree, including untracked ones."""
    try:
        base = git("merge-base", "HEAD", default_branch(root), root=root)[0]
    except (subprocess.CalledProcessError, IndexError):
        base = "HEAD"
    files = set(git("diff", "--name-only", base, root=root))
    files |= set(git("ls-files", "--others", "--exclude-standard", root=root))
    return sorted(files)


def fingerprint(code: list[str]) -> str:
    return hashlib.sha256("\n".join(sorted(code)).encode()).hexdigest()[:16]


def state_file(root: Path = ROOT) -> Path:
    """Where the hook remembers what it already asked about: inside .git, never committed."""
    return Path(git("rev-parse", "--absolute-git-dir", root=root)[0]) / "kb-capture-asked.json"


def already_asked(state: dict, session: str, fp: str) -> bool:
    return bool(session) and state.get(session) == fp


def hook_decision(event: dict, files: list[str], cfg: dict, state: dict | None = None) -> dict | None:
    """The Stop hook's JSON output, or None to let the session end quietly. Records what it asked
    about in `state` (session id -> fingerprint of the code files) so it asks once per change set."""
    if cfg["mode"] == "off" or event.get("stop_hook_active"):
        return None
    code, kb = classify(files, cfg["ignore"])
    if not code or (kb and cfg["has_kb"]):
        return None
    state = {} if state is None else state
    session, fp = event.get("session_id", ""), fingerprint(code)
    if already_asked(state, session, fp):
        return None
    if session:
        state[session] = fp
    reason = HOOK_REASON if cfg["has_kb"] else HOOK_REASON_NO_KB.format(
        kbs=", ".join(cfg["kb_repos"]) or "see .claude/kb-capture.toml")
    if cfg["mode"] == "warn":
        return {"systemMessage": "kb-capture (warn): " + reason}
    return {"decision": "block", "reason": reason}


def run_hook(stdin=sys.stdin, root: Path = ROOT) -> int:
    try:
        event = json.load(stdin)
    except (json.JSONDecodeError, ValueError):
        event = {}
    try:
        path = state_file(root)
        state = json.loads(path.read_text()) if path.exists() else {}
        out = hook_decision(event, session_changes(root), load_config(root), state)
        path.write_text(json.dumps(dict(list(state.items())[-50:])))
    except Exception as exc:  # a broken check must never trap a session
        print(f"kb-capture skipped: {exc}", file=sys.stderr)
        return 0
    if out:
        print(json.dumps(out))
    return 0


def pr_verdict(files: list[str], labels: list[str], body: str, author: str, cfg: dict) -> tuple[bool, str]:
    """(passes, message) for a pull request."""
    if author in BOT_AUTHORS:
        return True, f"Opened by {author}: family automation is exempt."
    code, kb = classify(files, cfg["ignore"])
    if not code:
        return True, "No code changes outside the knowledge base."
    if kb and cfg["has_kb"]:
        return True, "The PR changes the knowledge base."
    for url, repo in KB_LINK.findall(body or ""):
        if repo.lower() in cfg["kb_repos"]:
            return True, f"Lesson recorded at {url}."
    if NO_KB_LABEL in labels:
        if NO_KB_REASON.search(body or ""):
            return True, "Labelled no-kb, with a reason."
        return False, "Labelled no-kb but the PR body has no 'No KB entry: <reason>' line."
    where = ("a change under docs/knowledge/" if cfg["has_kb"]
             else "a 'KB: <link>' line to the lesson in " + (", ".join(cfg["kb_repos"]) or "the KB this repo feeds"))
    return False, (f"{len(code)} file(s) changed outside the knowledge base without {where} "
                   "(decision 0011). Record the lesson, or add the no-kb label and a "
                   "'No KB entry: <reason>' line to the PR body.")


def run_pr(base: str, root: Path = ROOT) -> int:
    event_path = os.environ.get("GITHUB_EVENT_PATH")
    pr = {}
    if event_path and Path(event_path).exists():
        pr = json.loads(Path(event_path).read_text()).get("pull_request", {})
    files = git("diff", "--name-only", f"{base}...HEAD", root=root)
    ok, msg = pr_verdict(files, [lb["name"] for lb in pr.get("labels", [])], pr.get("body") or "",
                         (pr.get("user") or {}).get("login", ""), load_config(root))
    print(msg if ok else f"::error::{msg}")
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="mode", required=True)
    sub.add_parser("hook", help="run as a Claude Code Stop hook")
    p = sub.add_parser("pr", help="check a pull request in CI")
    p.add_argument("--base", default="origin/main", help="the ref the PR merges into")
    args = ap.parse_args()
    return run_hook() if args.mode == "hook" else run_pr(args.base)


if __name__ == "__main__":
    sys.exit(main())
